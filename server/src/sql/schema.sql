-- 听着游管理后台 数据库结构（金额一律存分）
CREATE DATABASE IF NOT EXISTS tingzheyou_admin DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE tingzheyou_admin;

-- ---------- 系统 ----------

CREATE TABLE IF NOT EXISTS admin_user (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(50) NOT NULL UNIQUE COMMENT '登录账号',
  password_hash VARCHAR(100) NOT NULL,
  real_name VARCHAR(50) NOT NULL DEFAULT '' COMMENT '姓名',
  role_id INT UNSIGNED NOT NULL COMMENT '单角色',
  status TINYINT NOT NULL DEFAULT 1 COMMENT '1启用 0禁用',
  last_login_at DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='后台账号';

CREATE TABLE IF NOT EXISTS role (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(50) NOT NULL UNIQUE COMMENT '角色名称',
  remark VARCHAR(200) NOT NULL DEFAULT '' COMMENT '备注',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='角色';

CREATE TABLE IF NOT EXISTS menu (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  parent_id INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '0为一级',
  title VARCHAR(50) NOT NULL COMMENT '菜单名',
  path VARCHAR(100) NOT NULL DEFAULT '' COMMENT '前端路由',
  icon VARCHAR(50) NOT NULL DEFAULT '' COMMENT '图标名',
  sort INT NOT NULL DEFAULT 0,
  perm_code VARCHAR(50) NULL COMMENT '模块标识，接口鉴权用；目录为 NULL'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='菜单';

CREATE TABLE IF NOT EXISTS role_menu (
  role_id INT UNSIGNED NOT NULL,
  menu_id INT UNSIGNED NOT NULL,
  PRIMARY KEY (role_id, menu_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='角色-菜单';

CREATE TABLE IF NOT EXISTS op_log (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  admin_user_id INT UNSIGNED NULL,
  username VARCHAR(50) NOT NULL DEFAULT '',
  module VARCHAR(50) NOT NULL COMMENT '模块：scenic/product/pricing/redeem/order/user/recommend/content/system/auth',
  action VARCHAR(50) NOT NULL,
  target VARCHAR(200) NOT NULL DEFAULT '' COMMENT '操作对象',
  before_json JSON NULL COMMENT '变更前',
  after_json JSON NULL COMMENT '变更后',
  ip VARCHAR(50) NOT NULL DEFAULT '',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_module (module),
  KEY idx_username (username),
  KEY idx_created (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='操作日志';

CREATE TABLE IF NOT EXISTS sys_config (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  config_key VARCHAR(50) NOT NULL UNIQUE,
  config_value VARCHAR(500) NOT NULL DEFAULT '',
  remark VARCHAR(200) NOT NULL DEFAULT '',
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='系统配置';

CREATE TABLE IF NOT EXISTS region (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  code VARCHAR(20) NOT NULL UNIQUE COMMENT '行政区划代码',
  parent_code VARCHAR(20) NOT NULL DEFAULT '',
  name VARCHAR(50) NOT NULL,
  level TINYINT NOT NULL COMMENT '1省 2市',
  KEY idx_parent (parent_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='行政区划（省市两级）';

-- ---------- 景区 ----------

CREATE TABLE IF NOT EXISTS scenic_area (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL COMMENT '景区名称',
  description TEXT NULL COMMENT '景区描述',
  cover_image VARCHAR(500) NOT NULL DEFAULT '' COMMENT '封面图',
  broadcast_audio VARCHAR(500) NOT NULL DEFAULT '' COMMENT '播报内容（音频）',
  level VARCHAR(10) NOT NULL DEFAULT 'OTHER' COMMENT '5A/4A/OTHER',
  open_time VARCHAR(100) NOT NULL DEFAULT '' COMMENT '开门时间（文本）',
  province_code VARCHAR(20) NOT NULL DEFAULT '',
  city_code VARCHAR(20) NOT NULL DEFAULT '',
  address VARCHAR(200) NOT NULL DEFAULT '' COMMENT '景区地点',
  fence JSON NULL COMMENT '围栏：{type:"FREE",points:[{lng,lat}×4]} 或 {type:"RADIUS",center:{lng,lat},radius:米}，NULL=未设置',
  status TINYINT NOT NULL DEFAULT 1 COMMENT '1上架 0下架',
  is_deleted TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_level (level),
  KEY idx_province (province_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='景区';

CREATE TABLE IF NOT EXISTS scenic_spot (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  scenic_area_id INT UNSIGNED NOT NULL,
  name VARCHAR(100) NOT NULL COMMENT '景点名称',
  description TEXT NULL COMMENT '景点描述',
  image VARCHAR(500) NOT NULL DEFAULT '' COMMENT '景点图片',
  audio VARCHAR(500) NOT NULL DEFAULT '' COMMENT '讲解音频',
  narration TEXT NULL COMMENT '讲解词',
  fence JSON NULL COMMENT '围栏：{type:"FREE",points:[{lng,lat}×4]} 或 {type:"RADIUS",center:{lng,lat},radius:米}，NULL=未设置',
  is_audition TINYINT NOT NULL DEFAULT 0 COMMENT '试听：1是 0否',
  is_must_listen TINYINT NOT NULL DEFAULT 0 COMMENT '必听：1是 0否',
  is_deleted TINYINT NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_area (scenic_area_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='景点';

-- ---------- 商品 ----------

-- 商品仅承载基础对外展示信息；卡类型/有效期/库存/权益范围等履约配置在 SKU 维度
CREATE TABLE IF NOT EXISTS product (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL COMMENT '卡名称',
  subtitle VARCHAR(200) NOT NULL DEFAULT '' COMMENT '卡副标题',
  detail_images JSON NULL COMMENT '详情图',
  purchase_notice TEXT NULL COMMENT '购买须知',
  agreement TEXT NULL COMMENT '协议文本',
  status VARCHAR(20) NOT NULL DEFAULT 'OFF' COMMENT 'ON上架 OFF下架 HALTED停售',
  is_deleted TINYINT NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='商品（会员卡展示载体）';

CREATE TABLE IF NOT EXISTS product_sku (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  product_id INT UNSIGNED NOT NULL,
  card_type VARCHAR(20) NOT NULL DEFAULT 'DURATION' COMMENT 'DURATION时长卡 COUNT次卡',
  name VARCHAR(100) NOT NULL COMMENT '季卡/半年卡/年卡/永久卡/10次卡',
  duration_months INT NULL COMMENT '时长卡：3/6/12，0=永久（历史数据可能有1）',
  use_count INT NULL COMMENT '次卡：次数',
  valid_type VARCHAR(20) NOT NULL DEFAULT 'D365' COMMENT '次卡时间窗 D30/D365/PERMANENT',
  effective_mode VARCHAR(20) NOT NULL DEFAULT 'IMMEDIATE' COMMENT 'IMMEDIATE买后立即生效 SPECIFIED指定时间生效',
  effective_at DATETIME NULL COMMENT '指定时间生效时的时间点',
  auto_invalid TINYINT NOT NULL DEFAULT 1 COMMENT '过期自动失效',
  regions JSON NULL COMMENT '地理使用范围：["NATIONWIDE"] 或省市code数组',
  scope_type VARCHAR(20) NOT NULL DEFAULT 'LEVEL' COMMENT 'LEVEL按级别 SCENIC按景区（二选一）',
  scope_levels JSON NULL COMMENT '["5A","4A"]',
  scope_scenic_ids JSON NULL COMMENT '指定可用景区',
  platforms JSON NULL COMMENT '归属渠道：["MINI_PROGRAM","IOS","ANDROID","HARMONY","H5"]（历史数据可能含 APP，已迁移为 IOS）',
  discount INT NULL COMMENT '范围外折扣%（80=8折），NULL无',
  base_price INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '基础售价（分）',
  original_price INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '原价/划线价（分）',
  stock INT NULL COMMENT 'NULL=不限量',
  locked_count INT NOT NULL DEFAULT 0 COMMENT '下单锁定',
  sales_count INT NOT NULL DEFAULT 0 COMMENT '已售',
  is_deleted TINYINT NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_product (product_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='商品SKU（履约配置载体）';

-- ---------- 定价 ----------

CREATE TABLE IF NOT EXISTS price_plan (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL COMMENT '方案名称',
  priority INT NOT NULL DEFAULT 0 COMMENT '优先级（数值越大，命中优先级越高）',
  channel VARCHAR(20) NOT NULL DEFAULT 'ALL' COMMENT '适用渠道：ALL/MINI_PROGRAM/IOS/ANDROID/HARMONY/H5（仅作价格匹配条件，不能超出 SKU 可售卖渠道）',
  audience VARCHAR(30) NOT NULL DEFAULT 'ALL' COMMENT '适用人群：ALL=全部用户，NEW=新客，OLD=老客，EXPIRED_MEMBER=过期会员，AGENT=代理商',
  start_at DATETIME NOT NULL COMMENT '上线时间',
  end_at DATETIME NULL COMMENT '失效时间（NULL=长期有效）',
  status VARCHAR(20) NOT NULL DEFAULT 'DISABLED' COMMENT 'ENABLED/DISABLED（新建默认停用，手动启用后参与价格匹配）',
  created_by VARCHAR(50) NOT NULL DEFAULT '',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='定价方案（可跨商品绑定多SKU）';

CREATE TABLE IF NOT EXISTS price_plan_sku (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  plan_id INT UNSIGNED NOT NULL,
  sku_id INT UNSIGNED NOT NULL,
  original_price INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '原价（分）',
  sale_price INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '售价（分）',
  UNIQUE KEY uk_plan_sku (plan_id, sku_id),
  KEY idx_sku (sku_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='方案-SKU 绑定';

-- ---------- 兑换码 ----------

CREATE TABLE IF NOT EXISTS redeem_batch (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL COMMENT '批次名称',
  sku_id INT UNSIGNED NULL COMMENT '关联SKU，NULL=权益码（权益来自批次自身）',
  quantity INT UNSIGNED NOT NULL COMMENT '生成数量',
  valid_type VARCHAR(20) NOT NULL COMMENT 'M3/M6/Y1/PERMANENT',
  expire_at DATETIME NULL COMMENT 'NULL=无期限',
  regions JSON NULL COMMENT '["NATIONWIDE"]或省市code',
  levels JSON NULL COMMENT '["ALL"]/["5A","4A"]，指定景区模式为空',
  scenic_ids JSON NULL COMMENT '指定景区id数组（使用范围=指定景区时）',
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE/VOID',
  used_count INT UNSIGNED NOT NULL DEFAULT 0,
  created_by VARCHAR(50) NOT NULL DEFAULT '',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='兑换码批次';

CREATE TABLE IF NOT EXISTS redeem_code (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  batch_id INT UNSIGNED NOT NULL,
  code VARCHAR(10) NOT NULL UNIQUE COMMENT '8位，数字+大写字母（排除0/O/1/I）',
  status VARCHAR(20) NOT NULL DEFAULT 'UNUSED' COMMENT 'UNUSED/USED/VOID',
  used_by INT UNSIGNED NULL COMMENT '使用人（一人一码）',
  used_at DATETIME NULL,
  order_id BIGINT UNSIGNED NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_batch (batch_id),
  KEY idx_status (status),
  KEY idx_used_by (used_by)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='兑换码';

-- ---------- 用户 / 会员 / 订单 ----------

CREATE TABLE IF NOT EXISTS user (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  nickname VARCHAR(50) NOT NULL DEFAULT '',
  phone VARCHAR(20) NOT NULL DEFAULT '',
  avatar VARCHAR(500) NOT NULL DEFAULT '',
  channel VARCHAR(20) NOT NULL DEFAULT 'MINI_PROGRAM' COMMENT '注册渠道：MINI_PROGRAM/IOS/ANDROID/HARMONY/H5（历史数据可能含 APP，已迁移为 IOS）',
  registered_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_login_at DATETIME NULL,
  KEY idx_phone (phone)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='C端用户';

CREATE TABLE IF NOT EXISTS membership (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id INT UNSIGNED NOT NULL,
  product_id INT UNSIGNED NULL COMMENT '权益码兑换的会员无关联商品',
  sku_id INT UNSIGNED NULL COMMENT '权益码兑换的会员无关联SKU',
  source VARCHAR(20) NOT NULL DEFAULT 'PURCHASE' COMMENT 'PURCHASE购买/REDEEM兑换',
  order_id BIGINT UNSIGNED NULL,
  start_at DATETIME NOT NULL COMMENT '开卡生效时间',
  end_at DATETIME NULL COMMENT 'NULL=永久',
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE/EXPIRED/REFUNDED',
  remaining_count INT NULL COMMENT '次卡剩余次数',
  activated_at DATETIME NULL,
  scope_regions JSON NULL COMMENT '权益范围快照（商品权益∪批次范围）',
  scope_levels JSON NULL,
  scope_scenic_ids JSON NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_user (user_id),
  KEY idx_status (status),
  KEY idx_order (order_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='会员记录';

CREATE TABLE IF NOT EXISTS orders (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  order_no VARCHAR(32) NOT NULL UNIQUE,
  user_id INT UNSIGNED NOT NULL,
  type VARCHAR(20) NOT NULL COMMENT 'MEMBER_CARD 会员卡购买（仅此一种；历史数据可能存在 PHYSICAL/REDEEM）',
  channel VARCHAR(20) NOT NULL DEFAULT 'MINI_PROGRAM',
  product_id INT UNSIGNED NULL,
  sku_id INT UNSIGNED NULL,
  sku_name VARCHAR(100) NOT NULL DEFAULT '' COMMENT '订单项快照',
  sku_snapshot JSON NULL COMMENT '下单时SKU权益配置快照（会员开卡以此为准，SKU后续变更不影响）',
  original_price INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '原价（分）',
  pay_amount INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '实付（分）',
  pay_status VARCHAR(20) NOT NULL DEFAULT 'UNPAID' COMMENT 'UNPAID/PAID/PAY_FAILED/REFUNDED/PART_REFUNDED',
  fulfill_status VARCHAR(20) NOT NULL DEFAULT 'NONE' COMMENT 'NONE/WAIT_ACTIVATE/ACTIVATED/EXCHANGED',
  pay_method VARCHAR(20) NOT NULL DEFAULT '' COMMENT 'WECHAT/REDEEM_CODE',
  paid_at DATETIME NULL,
  close_type VARCHAR(20) NULL COMMENT 'USER_CANCEL/ADMIN_CANCEL/TIMEOUT',
  cancel_reason VARCHAR(200) NOT NULL DEFAULT '',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_user (user_id),
  KEY idx_pay (pay_status),
  KEY idx_type (type),
  KEY idx_created (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='订单';

CREATE TABLE IF NOT EXISTS order_refund (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  order_id BIGINT UNSIGNED NOT NULL,
  admin_user_id INT UNSIGNED NULL,
  amount INT UNSIGNED NOT NULL COMMENT '退款金额（分）',
  reason VARCHAR(200) NOT NULL DEFAULT '',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_order (order_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='退款记录';

-- ---------- 推荐管理 ----------

CREATE TABLE IF NOT EXISTS recommendation (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  spot_id INT UNSIGNED NOT NULL COMMENT '景点id（必填）',
  title VARCHAR(100) NOT NULL DEFAULT '' COMMENT '为空时从景点回填',
  summary VARCHAR(500) NOT NULL DEFAULT '',
  cover VARCHAR(500) NOT NULL DEFAULT '',
  weight INT NOT NULL DEFAULT 0 COMMENT '越大越靠前',
  is_deleted TINYINT NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_weight (weight)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='精选免费听推荐位';

-- ---------- 线路管理 ----------

CREATE TABLE IF NOT EXISTS scenic_route (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  scenic_area_id INT UNSIGNED NOT NULL COMMENT '所属景区',
  name VARCHAR(100) NOT NULL COMMENT '线路名称',
  is_deleted TINYINT NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_area (scenic_area_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='景区线路';

CREATE TABLE IF NOT EXISTS scenic_route_spot (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  route_id INT UNSIGNED NOT NULL COMMENT '所属线路',
  scenic_spot_id INT UNSIGNED NOT NULL COMMENT '景点',
  sort_order INT NOT NULL DEFAULT 0 COMMENT '景点顺序（数值越小越靠前）',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uk_route_spot (route_id, scenic_spot_id),
  KEY idx_route (route_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='线路-景点（有序，不影响景区景点本身）';

-- ---------- 内容位（广告 / 首页轮播图） ----------

CREATE TABLE IF NOT EXISTS content_slot (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  type VARCHAR(20) NOT NULL COMMENT 'AD广告 / BANNER首页轮播图',
  title VARCHAR(100) NOT NULL COMMENT '标题',
  image VARCHAR(500) NOT NULL DEFAULT '' COMMENT '图片',
  link_type VARCHAR(20) NOT NULL DEFAULT 'H5' COMMENT 'H5链接 / MINI_PROGRAM小程序链接',
  link_url VARCHAR(500) NOT NULL DEFAULT '' COMMENT '对应链接',
  weight INT NOT NULL DEFAULT 0 COMMENT '排序权重（越大越靠前）',
  is_deleted TINYINT NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_type (type)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='内容位（广告与首页轮播图统一表）';
